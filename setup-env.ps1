# BIMcred - interactive .env setup (Windows PowerShell)
#
# Run:  powershell -ExecutionPolicy Bypass -File .\setup-env.ps1
#
# It asks for the two Neon connection strings, adds the serverless parameters
# to the pooled URL, generates a fresh SESSION_SECRET, and writes .env.

$ErrorActionPreference = "Stop"
Set-Location $PSScriptRoot

function Read-Url([string]$Prompt) {
  $secure = Read-Host -AsSecureString $Prompt
  return [System.Net.NetworkCredential]::new('', $secure).Password
}

$pooled = (Read-Url "Paste the POOLED connection string (Connection pooling ON):").Trim()
$direct = (Read-Url "Paste the DIRECT connection string (Connection pooling OFF):").Trim()

if ($pooled -notmatch '^postgresql://' -or $direct -notmatch '^postgresql://') {
  throw "Both values must start with postgresql://"
}

# The pooled URL must carry Prisma's serverless flags. Keep channel_binding etc.
if ($pooled -notmatch 'pgbouncer=true') {
  $separator = if ($pooled.Contains('?')) { '&' } else { '?' }
  $pooled = "$pooled$separator" + "pgbouncer=true&connection_limit=5"
}
$pooled = $pooled -replace 'connection_limit=\d+', 'connection_limit=5'

# Be forgiving if the direct URL was copied with pooling still on.
$direct = $direct -replace '-pooler\.', '.'

if ($pooled -notmatch '-pooler') {
  Write-Warning "The pooled URL does not contain '-pooler'. Check you copied the ON version."
}
if ($direct -match '-pooler') {
  throw "The direct URL still contains '-pooler'. Copy the OFF version."
}

$bytes = New-Object byte[] 32
[System.Security.Cryptography.RandomNumberGenerator]::Create().GetBytes($bytes)
$secret = [Convert]::ToBase64String($bytes)

$envContent = @"
# BIMcred local environment - generated by setup-env.ps1 (gitignored)
DATABASE_URL="$pooled"
DIRECT_URL="$direct"
SESSION_SECRET="$secret"
APP_URL="http://localhost:3000"
NODE_ENV="development"
DEV_SHOW_OTP="true"
"@

Set-Content -Path ".env" -Value $envContent -Encoding UTF8

Write-Host "`n[bimcred] .env written. Pooled host: " -NoNewline -ForegroundColor Green
if ($pooled -match '@([^/]+)/') { Write-Host $Matches[1] -ForegroundColor Green } else { Write-Host "(unknown)" }
Write-Host "[bimcred] Direct host: " -NoNewline -ForegroundColor Green
if ($direct -match '@([^/]+)/') { Write-Host $Matches[1] -ForegroundColor Green } else { Write-Host "(unknown)" }
Write-Host "[bimcred] Next: powershell -ExecutionPolicy Bypass -File .\\run.ps1`n" -ForegroundColor Green
